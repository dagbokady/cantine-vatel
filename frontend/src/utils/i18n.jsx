// Ajouter une langue : un dictionnaire ci-dessus + une ligne ici (les clés manquantes retombent sur le français).
export const LANGUES = [
  { code: "fr", nom: "Français", locale: "fr-FR" },
  { code: "en", nom: "English", locale: "en-GB" },
  { code: "es", nom: "Español", locale: "es-ES" },
  { code: "pt", nom: "Português", locale: "pt-PT" },
  { code: "de", nom: "Deutsch", locale: "de-DE" },
];

export const localeDe = (code) => (LANGUES.find((l) => l.code === code) || LANGUES[0]).locale;

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const l = localStorage.getItem("lang");
    return LANGUES.some((x) => x.code === l) ? l : "fr";
  });

  useEffect(() => {
    localStorage.setItem("lang", lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const t = useCallback(
    (key) => (DICT[lang] && DICT[lang][key]) || DICT.fr[key] || key,
    [lang],
  );

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
